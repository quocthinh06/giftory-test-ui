require('reflect-metadata');
const assert = require('node:assert/strict');
const { CartService } = require('../dist/modules/cart/cart.service');
const { OrdersService } = require('../dist/modules/orders/orders.service');
const id = '507f1f77bcf86cd799439011';
const product = { _id: id, name: 'Gift', price: 100000, stock: 20, images: [], isCustomizable: true, variants: [] };
const cart = { items: [], save: async () => {} };
const service = new CartService({}, { findById: async () => product }, {});
service.findOrCreateCart = async () => cart;
service.getCart = async () => cart;
const box = (id, styleId = 'cream') => ({ id, styleId, styleName: 'untrusted' });
(async () => {
  await service.addItem({ productId: id, quantity: 1 });
  await service.addItem({ productId: id, quantity: 1, customDetails: { setbox: box('box-a') } });
  await service.addItem({ productId: id, quantity: 1, customDetails: { setbox: box('box-b', 'walnut') } });
  assert.equal(cart.items.length, 3, 'loose items and different boxes stay separate');
  assert.equal(cart.items[1].isCustom, false, 'box selection alone does not trigger a deposit');
  assert.equal(cart.items[1].customDetails.setbox.styleName, 'Kem thanh lịch');
  await service.addItem({ productId: id, quantity: 1, customDetails: { setbox: box('box-a') } });
  assert.equal(cart.items[1].quantity, 2, 'same box can merge matching ordinary items');
  await assert.rejects(service.addItem({ productId: id, quantity: 1, customDetails: { setbox: box('box-c', 'fake') } }));
  const details = { frontMessage: 'Giftory', customFee: 20000, textBlocks: [{ text: 'Giftory', x: 12, y: 40 }], setbox: box('box-a') };
  await service.addItem({ productId: id, quantity: 1, customDetails: details });
  const index = cart.items.length - 1;
  assert.equal(cart.items[index].price, 120000);
  assert.equal(cart.items[index].depositRequired, 60000);
  await service.updateItemCustomDetails(index, { frontMessage: 'Updated', customFee: 40000 });
  assert.equal(cart.items[index].customDetails.setbox.id, 'box-a', 'editing in Studio keeps box membership');
  const populated = cart.items.map(item => ({ ...item, productId: product }));
  const orderCart = { items: populated, save: async () => {} };
  const orders = new OrdersService(null, { create: async payload => payload }, { findOne: () => ({ populate: async () => orderCart }) }, null, null, null);
  const order = await orders.createOrder({ sessionId: 'test', paymentMethod: 'COD', shippingMethod: 'STANDARD' });
  assert.equal(order.pricing.depositAmount, 70000, 'only half of the customized line is prepaid');
  assert.equal(order.items[1].customDetails.setbox.id, 'box-a');
  assert.equal(order.items[index].customDetails.frontMessage, 'Updated');
  console.log('Setbox: grouping, trusted style names, validation, Studio edit, order metadata and custom-only 50% deposit passed');
})().catch(error => { console.error(error); process.exitCode = 1; });
